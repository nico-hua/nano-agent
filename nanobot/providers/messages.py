"""Vendor-neutral chat message types for LLM providers."""

from __future__ import annotations

from abc import ABC, abstractmethod
from collections.abc import Mapping
from dataclasses import dataclass, field
from typing import Any, Literal

MessageRole = Literal["system", "user", "assistant", "tool"]


@dataclass(frozen=True)
class ToolCallRequest:
    """A request from the model to invoke a tool."""

    id: str
    name: str
    arguments: Mapping[str, Any]


@dataclass(frozen=True)
class BaseMessage(ABC):
    """Base class for messages passed to an LLM provider."""

    content: str
    is_visible: bool = field(default=True, kw_only=True)

    def __post_init__(self) -> None:
        """Require a boolean visibility flag for display and evidence filtering."""
        if not isinstance(self.is_visible, bool):
            raise TypeError("is_visible must be a boolean")

    @property
    @abstractmethod
    def role(self) -> MessageRole:
        """Return the provider-neutral role of this message."""

        raise NotImplementedError


@dataclass(frozen=True)
class SystemMessage(BaseMessage):
    """A message that provides instructions or context to the model."""

    @property
    def role(self) -> Literal["system"]:
        """Identify instructions when serializing a provider-neutral message."""
        return "system"


@dataclass(frozen=True)
class HumanMessage(BaseMessage):
    """A message from the user."""

    @property
    def role(self) -> Literal["user"]:
        """Identify user input for turn grouping and provider serialization."""
        return "user"


@dataclass(frozen=True)
class AIMessage(BaseMessage):
    """A message generated by the model, optionally requesting tools."""

    tool_calls: tuple[ToolCallRequest, ...] = ()

    @property
    def role(self) -> Literal["assistant"]:
        """Identify assistant text and tool requests when serializing a conversation."""
        return "assistant"


@dataclass(frozen=True)
class ToolMessage(BaseMessage):
    """A tool result associated with a previous model tool call."""

    tool_call_id: str

    @property
    def role(self) -> Literal["tool"]:
        """Identify tool output associated with a preceding tool call."""
        return "tool"


# Keep the existing name available for type annotations during the migration
# to the more specific message classes.
Message = BaseMessage


def message_record(message: BaseMessage) -> dict[str, Any]:
    """Serialize message content and tool metadata for use as evidence."""
    record: dict[str, Any] = {"role": message.role, "content": message.content}
    if isinstance(message, AIMessage) and message.tool_calls:
        record["tool_calls"] = [
            {"id": call.id, "name": call.name, "arguments": dict(call.arguments)}
            for call in message.tool_calls
        ]
    elif isinstance(message, ToolMessage):
        record["tool_call_id"] = message.tool_call_id
    return record
